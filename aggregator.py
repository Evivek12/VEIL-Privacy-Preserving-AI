
import requests


OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL_NAME = "llama3.2:3b"


def get_final_answer(original_query: str, safe_prompt: str, route: str) -> str:
    """
    Generate an answer using the local Ollama model.
    Only the sanitized prompt is sent to Ollama.
    """

    try:
        response = requests.post(
            OLLAMA_URL,
            json={
                "model": MODEL_NAME,
                "prompt": safe_prompt,
                "stream": False
            },
            timeout=180
        )

        response.raise_for_status()

        result = response.json()

        return result.get(
            "response",
            "No response generated by the local model."
        )

    except requests.exceptions.ConnectionError:
        return (
            "Ollama is not running. Please start Ollama "
            "and try again."
        )

    except requests.exceptions.Timeout:
        return "The local AI model took too long to respond."

    except requests.exceptions.RequestException as error:
        return f"AI model error: {error}"
